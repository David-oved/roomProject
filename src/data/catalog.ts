import type { Agorot, Category } from '../types/models';

/**
 * ═══════════════════════════════════════════════════════════════════
 *  קטלוג מוצרי הבסיס
 * ═══════════════════════════════════════════════════════════════════
 *
 *  למה הקטלוג יושב בקוד ולא ב-Firebase:
 *   · ~200 מוצרים = ~200 כתיבות ואלפי קריאות, בלי שום תמורה
 *   · נטען מיידית, בלי latency ובלי מסך טעינה
 *   · עובד גם ללא רשת, בכל מכשיר, מהרגע הראשון
 *   · שינוי הרשימה = שחרור גרסה, שממילא קורה
 *
 *  מה כן יושב ב-Firebase:
 *   · /catalog                    — מוצרים שמשתמשים הוסיפו (גלובלי, לכל החדרים)
 *   · /rooms/{code}/catalogPrices — עקיפת מחיר, פר-חדר בלבד
 *   · /rooms/{code}/staples       — אילו מוצרים החדר מגדיר כבסיס
 *
 *  המחירים הם הערכה בשקלים נכון ל-2026, כנקודת פתיחה בלבד.
 *  כל חדר מכוון אותם לעצמו בלי להשפיע על אחרים.
 * ═══════════════════════════════════════════════════════════════════
 */

export interface CatalogProduct {
  /** מזהה יציב באנגלית — משמש כמפתח ב-Firebase */
  id: string;
  name: string;
  category: Category;
  /** יחידת מידה להצגה */
  unit?: string;
  /** מחיר משוער באגורות */
  defaultPrice: Agorot;
  /** true = מהקטלוג המובנה. אחרת — נוסף ע"י משתמש */
  seed?: true;
}

/** [id, שם, מחיר בשקלים, יחידה?] */
type Row = [string, string, number, string?];

const build = (rows: Row[], category: Category): CatalogProduct[] =>
  rows.map(([id, name, price, unit]) => ({
    id,
    name,
    category,
    defaultPrice: Math.round(price * 100),
    ...(unit ? { unit } : {}),
    seed: true as const,
  }));

